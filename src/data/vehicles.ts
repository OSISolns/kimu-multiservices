// Function to check if a vehicle is available based on current bookings
export function checkVehicleAvailability(vehicleName: string, bookings: any[] = []): boolean {
  const now = new Date();
  const today = now.toISOString().split('T')[0];
  
  // Check if vehicle has any active bookings
  const activeBookings = bookings.filter(booking => {
    // Skip confirmed returns
    if (booking.returnConfirmed) return false;
    
    // Check if booking is for this vehicle
    if (booking.carType !== vehicleName) return false;
    
    // Check if booking is active (current date is within rental period)
    const pickupDate = booking.pickupDate;
    const returnDate = booking.returnDate;
    
    if (!pickupDate || !returnDate) return false;
    
    // If return date is in the future, vehicle is rented
    if (returnDate > today) return true;
    
    // If return date is today, check return time
    if (returnDate === today && booking.returnTime) {
      const returnTime = new Date(`${returnDate}T${booking.returnTime}`);
      return now < returnTime;
    }
    
    return false;
  });
  
  return activeBookings.length === 0;
}

// Function to get vehicles with availability status
export function getVehiclesWithAvailability(bookings: any[] = []): any[] {
  return vehicles.map(vehicle => ({
    ...vehicle,
    isAvailable: checkVehicleAvailability(vehicle.name, bookings)
  }));
} 